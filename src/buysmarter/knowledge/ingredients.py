"""Per-category active-ingredient knowledge for composition-driven categories.

For cosmetics / pharmacy / supplements the **active substance** (and its
concentration) often matters more than the brand: Клензит 0,1% and Differin are
the *same* adapalene at a 4x price gap (docs/PLAN.md "Composition-driven
категории"). An ``IngredientBook`` names the canonical active substances of a
category, their spelling/brand aliases, typical concentrations, and the known
generic-equivalence groups (products sharing a substance at a concentration).

Generated by ``opus`` for composition-driven categories (from the model's own
scientific knowledge) and stored inside ``CategoryKnowledge`` alongside the
BrandBook/ModelBook; merged on ``learn`` like the other books.
"""

from __future__ import annotations

import re

from pydantic import BaseModel, Field


def normalize_concentration(text: str | None) -> str | None:
    """Canonical form of a concentration string ("0,1 %" / "0.1%" → "0.1%")."""
    if not text:
        return None
    cleaned = re.sub(r"\s+", "", text.strip().lower()).replace(",", ".")
    return cleaned or None


def _normalize(text: str) -> str:
    """Lowercase; used for substring matching of substance names in free text."""
    return text.lower()


# Spec keys that carry a composition/INCI list; first hit wins. Shared by the
# extraction step (services) and the ranking hard filter/axis (engine) so the
# "does this candidate even declare a состав?" question has one answer.
COMPOSITION_SPEC_KEYS = ("Состав", "состав", "Ingredients", "INCI")


def composition_text(specs: dict[str, str]) -> str:
    """The candidate's composition/состав text, if any spec key carries it."""
    for key in COMPOSITION_SPEC_KEYS:
        value = specs.get(key)
        if value:
            return value
    return ""


class EquivalentProduct(BaseModel):
    """A known product sharing a substance (a member of a generic-equivalence group)."""

    name: str
    concentration: str | None = None


class ActiveSubstance(BaseModel):
    """One canonical active substance + its aliases, concentrations, equivalents."""

    canonical: str
    aliases: list[str] = Field(default_factory=list)
    typical_concentrations: list[str] = Field(default_factory=list)
    equivalents: list[EquivalentProduct] = Field(default_factory=list)

    def matches(self, text_lower: str) -> bool:
        """True if the canonical name or any alias appears in ``text_lower``.

        Substring (not whole-word) match on purpose: Russian declensions
        ("адапаленом", "адапалена") must still resolve to "адапален", and
        substance names are distinctive enough that substring is safe.
        """
        needles = [self.canonical, *self.aliases]
        return any(_normalize(n) in text_lower for n in needles if n)


class IngredientBook(BaseModel):
    """Canonical active substances of one composition-driven category."""

    substances: list[ActiveSubstance] = Field(default_factory=list)

    def canonical_for(self, name: str) -> str | None:
        """Resolve a raw substance name (canonical or alias) to its canonical form."""
        lowered = _normalize(name)
        for substance in self.substances:
            if _normalize(substance.canonical) == lowered:
                return substance.canonical
            if any(_normalize(a) == lowered for a in substance.aliases):
                return substance.canonical
        return None

    def resolve_in_text(self, text: str) -> list[str]:
        """Canonical substances whose name/alias appears in ``text`` (query/title)."""
        lowered = _normalize(text)
        return [s.canonical for s in self.substances if s.matches(lowered)]

    def _substance(self, canonical: str) -> ActiveSubstance | None:
        return next((s for s in self.substances if s.canonical == canonical), None)

    def search_terms_for(self, canonical: str) -> list[str]:
        """Recall search queries for a required substance (docs/PLAN.md).

        The substance name itself plus every known equivalence-group product name
        («адапален», «Клензит», «Дифферин», «Адаклин»...) — deduped, first-seen
        order — so a marketplace search that missed the bare substance still
        surfaces the branded generics that actually carry it.
        """
        substance = self._substance(canonical)
        if substance is None:
            return [canonical]
        terms = [substance.canonical, *(e.name for e in substance.equivalents)]
        return list(dict.fromkeys(t for t in terms if t))

    def title_needles_for(self, canonical: str) -> list[str]:
        """Every name that, in a card title, confirms a card is about this substance."""
        substance = self._substance(canonical)
        if substance is None:
            return [canonical]
        needles = [
            substance.canonical,
            *substance.aliases,
            *(e.name for e in substance.equivalents),
        ]
        return list(dict.fromkeys(n for n in needles if n))


def merge_ingredient_books(base: IngredientBook, overlay: IngredientBook) -> IngredientBook:
    """Merge two IngredientBooks by canonical substance; ``overlay`` wins on conflicts."""
    by_canonical: dict[str, ActiveSubstance] = {s.canonical: s for s in base.substances}
    for substance in overlay.substances:
        by_canonical[substance.canonical] = substance
    return IngredientBook(substances=list(by_canonical.values()))
